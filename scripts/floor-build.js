import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { projectRoot } from '../src/mcp/channel.js';

// No dependencies or network: bundle our ES modules as a classic script for file://.
const folder = join(projectRoot, 'public/floor');
const sources = ['state.js', 'characters.js', 'scene.js', 'app.js'].map(name =>
  readFileSync(join(folder, name), 'utf8').replace(/^import .* from .*;\r?\n/gm, '').replace(/^export /gm, ''));
writeFileSync(join(folder, 'runtime.js'), `// Generated by node scripts/floor-build.js. Edit the source modules.\n(() => {\n'use strict';\n${sources.join('\n')}\n})();\n`);
console.log('Built public/floor/runtime.js (offline, no dependencies).');
